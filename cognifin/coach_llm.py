"""LLM-driven coach.

Pipeline: structured profile tags + live game event -> prompt -> LLM -> validated message.
The "Why this?" panel is assembled deterministically from the knowledge base and the user
model (metacognitive transparency), not generated by the LLM.

If GEMINI_API_KEY or GOOGLE_API_KEY is not set (or the call fails / the output is rejected), an offline
structured generator produces the message from the same inputs so the demo always runs.
The coach reports which source produced each message ("llm" vs "offline-generator").
"""
import json
import os
import re
import time
import urllib.error
import urllib.request

from .knowledge import TRAITS, EVENT_TO_TRAIT

API_URL = "https://generativelanguage.googleapis.com/v1beta/models"
DEFAULT_MODEL = "gemini-3-flash-preview"
# Used when the primary model is rate-limited, overloaded or retired; Google recommends it for
# new users (gemini-2.5-flash now returns 404 "no longer available to new users").
DEFAULT_FALLBACK_MODEL = "gemini-3.8-flash"
# Gemini 3 models always "think", and thinking tokens count against maxOutputTokens.
# A short coaching message needs little reasoning, so request a low thinking level and
# leave enough output budget that the visible answer is never truncated.
DEFAULT_THINKING_LEVEL = "low"
MAX_OUTPUT_TOKENS = 1024
RETRY_WAIT_S = 1.5


def _model():
    return os.environ.get("COGNIFIN_MODEL") or DEFAULT_MODEL


SYSTEM_PROMPT = (
    "You are CogniFin Coach, a supportive financial-decision coach inside a SIMULATED "
    "investing game that uses synthetic prices. Explain, in 2-3 short sentences, which "
    "psychological bias may be driving the player's last decision, using the player's own "
    "numbers. Address the player as 'you'. Be warm, concrete and non-judgmental. "
    "Mention a mismatch between what they said in the quiz and what they did only if one "
    "is provided. Rules: do not give real-world investment advice, do not predict future "
    "prices, do not recommend specific securities, do not shame the player, no bullet "
    "points, maximum 70 words."
)

FORBIDDEN = re.compile(r"\b(guarantee[sd]?|will (rise|fall|crash|recover)|you should buy|you must sell)\b", re.I)

EVENT_MECHANISMS = {
    "panic_sell": (
        "The rule flags a sale of at least half a holding after a sharp drop while "
        "the holding is below its average cost. Loss aversion or a desire to reduce "
        "immediate stress can be relevant, but the rule cannot identify your motive."
    ),
    "fomo_buy": (
        "The rule flags a buy of at least 30% of starting cash after a non-bond asset "
        "has risen at least 10% over three turns. Recent gains can make the possibility "
        "of missing further gains more salient."
    ),
    "overconcentration": (
        "The rule flags a buy that leaves more than 70% of portfolio value in one risky "
        "asset. Confidence in a single choice can make its uncertainty less noticeable."
    ),
    "overtrading": (
        "The rule flags trading on five consecutive turns. Repeated decisions can reflect "
        "an effort to time changing prices, though activity alone does not establish why "
        "you traded."
    ),
    "hold_loser": (
        "The rule flags a risky holding that is at least 10% below its average cost for "
        "about three turns. The purchase price can become an anchor, even though it does "
        "not by itself determine what to do next."
    ),
    "early_profit_take": (
        "The rule flags selling at least half of a small gain while another holding is "
        "at least 10% below its average cost. Treating gains and losses differently can "
        "be one explanation for that contrast."
    ),
}

REFLECTION_QUESTIONS = {
    "panic_sell": "What information besides the recent price drop mattered to your sell decision?",
    "fomo_buy": "If the recent gains were hidden, would you still have made this buy?",
    "overconcentration": "How would your portfolio be affected if this asset moved against you?",
    "overtrading": "What new information or plan change preceded each of the recent trades?",
    "hold_loser": "If you had today's cash now, would you choose this holding at today's price?",
    "early_profit_take": "Would you apply the same sell rule to your other holding?",
}


def _event_evidence(event):
    """Translate detector fields into a readable account of what triggered the rule."""
    event_type = event["type"]
    if event_type == "panic_sell":
        return (f"Sold {event['asset']} after a {abs(event['drop_pct']):.1f}% drop; "
                f"it was {abs(event['loss_vs_cost_pct']):.1f}% below average cost.")
    if event_type == "fomo_buy":
        return (f"Bought {event['asset']} after it rose "
                f"{event['recent_gain_pct']:.1f}% over three turns.")
    if event_type == "overconcentration":
        return (f"After buying {event['asset']}, it represented "
                f"{event['weight_pct']}% of portfolio value.")
    if event_type == "overtrading":
        return f"Traded on {event['trades_in_last_5']} consecutive turns."
    if event_type == "hold_loser":
        return (f"Held {event['asset']} while it was "
                f"{abs(event['loss_vs_cost_pct']):.1f}% below average cost for "
                f"{event['turns']} turns.")
    if event_type == "early_profit_take":
        return (f"Sold {event['asset']} at a {event['gain_pct']:.1f}% gain while "
                f"{event['loser']} was still held below cost.")
    raise ValueError(f"unsupported coaching event: {event_type}")


def build_prompt(user_model, event, mismatches):
    """Structured user prompt: profile tags + short-term context + event + mismatch."""
    trait = EVENT_TO_TRAIT[event["type"]]
    payload = {
        "decision_event": event,
        "bias_hypothesis": TRAITS[trait]["label"],
        "long_term_profile": {k: user_model.intensity(k) for k in user_model.long_term},
        "short_term_context": {
            "portfolio_drawdown_pct": round(user_model.short_term["drawdown"] * 100, 1),
            "decided_quickly": user_model.short_term["hasty"],
            "trait_estimate_uncertainty": user_model.uncertainty(trait),
            "recent_mistake_types": user_model.short_term["recent_events"],
        },
        "quiz_vs_behaviour_mismatches": [
            {"claimed": m["claim"], "did": m["behaviour"]} for m in mismatches
        ],
    }
    return json.dumps(payload, indent=2)


# ---------------------------------------------------------------------------
def _offline_message(user_model, event, mismatches):
    """Deterministic, profile-conditioned generator (used when no API key is available)."""
    t = event["type"]
    trait = EVENT_TO_TRAIT[t]
    inten = user_model.intensity(trait)
    hasty = user_model.short_term["hasty"]
    lead = {"high": "This looks like a pattern for you: ", "moderate": "",
            "low": "This may be a one-off for you: "}[inten]

    if t == "panic_sell":
        body = (f"you sold {event['asset']} right after it dropped {abs(event['drop_pct'])}%, "
                f"which locked in a {abs(event['loss_vs_cost_pct'])}% loss versus your cost. "
                "That is a typical fast, emotional reaction to a sudden fall.")
        tip = "Next time, pause one turn and ask whether anything about the asset itself has changed."
    elif t == "fomo_buy":
        body = (f"you bought {event['asset']} after it already gained {event['recent_gain_pct']}%. "
                "Part of the pull may be the fear of missing out on a rally others are riding.")
        tip = "Try a smaller position and decide in advance what price would make you wrong."
    elif t == "overconcentration":
        body = (f"{event['weight_pct']}% of your portfolio now sits in {event['asset']}. "
                "Strong conviction can feel like knowledge, but it also concentrates your risk.")
        tip = "Consider capping any single risky holding at a level you pick before the next swing."
    elif t == "overtrading":
        body = ("you have traded five turns in a row. Frequent trading often reflects confidence "
                "in timing the market, yet it tends to add cost rather than return.")
        tip = "Try skipping a turn on purpose to see whether holding changes how you feel."
    elif t == "hold_loser":
        body = (f"{event['asset']} has stayed {abs(event['loss_vs_cost_pct'])}% below your cost for "
                f"{event['turns']} turns. Waiting for it to 'get back to even' is a common way "
                "losses feel hard to accept.")
        tip = "Judge it as if you were choosing it fresh today, ignoring what you paid."
    else:  # early_profit_take
        body = (f"you cashed out a small {event['gain_pct']}% gain on {event['asset']} while "
                f"keeping {event['loser']}, which is down. Taking sure wins while holding losers "
                "is the classic disposition pattern.")
        tip = "Apply the same rule to winners and losers: would you buy it today?"

    pressure = " You also decided quickly, which makes gut reactions more likely." if hasty and t in ("panic_sell", "fomo_buy") else ""
    mm = ""
    if mismatches:
        m = mismatches[0]
        mm = f" In the quiz you said you {m['claim']}, but here you {m['behaviour']}."
    text = f"{lead}{body}{pressure}{mm} {tip}".replace("  ", " ").strip()
    return text[0].upper() + text[1:]


def _models():
    """Primary model, then a fallback model (Gemini quotas are counted per model)."""
    primary = _model()
    fallback = os.environ.get("COGNIFIN_FALLBACK_MODEL", DEFAULT_FALLBACK_MODEL).strip()
    return [primary] + ([fallback] if fallback and fallback.lower() != "none" and fallback != primary else [])


LAST_MODEL = None       # which model produced the most recent accepted reply (for logging/eval)


def _call_llm(system, user_text, timeout=15):
    """Try the primary model (one retry on 429/5xx), then the fallback model once.
    Returns the reply text, or None so the caller uses the labelled offline generator."""
    global LAST_MODEL
    LAST_MODEL = None
    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not key:
        return None
    generation = {"maxOutputTokens": MAX_OUTPUT_TOKENS, "temperature": 0.7}
    level = os.environ.get("COGNIFIN_THINKING_LEVEL", DEFAULT_THINKING_LEVEL).strip()
    if level and level.lower() != "default":
        generation["thinkingConfig"] = {"thinkingLevel": level}
    body = json.dumps({
        "system_instruction": {"parts": [{"text": system}]},
        "contents": [{"role": "user", "parts": [{"text": user_text}]}],
        "generationConfig": generation,
    }).encode()
    plan = []
    for i, model in enumerate(_models()):
        plan += [model, model] if i == 0 else [model]
    for n, model in enumerate(plan):
        req = urllib.request.Request(f"{API_URL}/{model}:generateContent", data=body, method="POST",
                                     headers={"x-goog-api-key": key, "content-type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=timeout) as r:
                data = json.loads(r.read().decode())
            text = _extract_text(data)
            if text:
                LAST_MODEL = model
            return text
        except urllib.error.HTTPError as e:
            if e.code not in (429, 500, 503):
                if e.code == 404 and n < len(plan) - 1:       # model retired -> try the next one
                    continue
                return None
        except Exception:       # timeout / network error -> try the next model
            pass
        if n < len(plan) - 1 and plan[n + 1] == model:
            time.sleep(RETRY_WAIT_S)
    return None


def _extract_text(data):
    """Visible answer text, or None if the reply was blocked or cut off (e.g. MAX_TOKENS)."""
    candidates = data.get("candidates") or []
    if not candidates:
        return None
    cand = candidates[0]
    if cand.get("finishReason") not in (None, "STOP"):
        return None
    parts = cand.get("content", {}).get("parts", [])
    return "".join(p.get("text", "") for p in parts
                   if isinstance(p, dict) and not p.get("thought")).strip() or None


def _valid(text):
    return bool(text) and len(text.split()) <= 110 and not FORBIDDEN.search(text)


def why_this(user_model, event, mismatches):
    event_type = event["type"]
    trait = EVENT_TO_TRAIT[event_type]
    kb = TRAITS[trait]
    trait_score = user_model.long_term[trait]
    quiz_score = user_model.quiz_traits[trait]
    sd = user_model.uncertainty(trait)
    n_obs = user_model.n_observations(trait)
    fired, _resisted = user_model.evidence[trait]
    return {
        "trait": kb["label"],
        "trait_definition": kb["definition"],
        "trait_score": trait_score,
        "quiz_score": quiz_score,
        "intensity": user_model.intensity(trait),
        "trait_uncertainty": sd,
        "evidence_count": n_obs,
        "triggered_by": event,
        "event_evidence": _event_evidence(event),
        "event_mechanism": EVENT_MECHANISMS[event_type],
        "profile_note": (
            f"The quiz starting score was {quiz_score:.0%}; the current adaptive "
            f"estimate is {trait_score:.0%} \u00b1 {sd:.0%} ({user_model.intensity(trait)}), "
            f"after {n_obs} observed opportunit{'y' if n_obs == 1 else 'ies'} "
            f"({int(fired)} where the pattern appeared). These are model estimates "
            "inside a simulation, not diagnoses."
        ),
        "research": kb["finding"],
        "citation": kb["citation"],
        "limitations": (
            "This is a rule-based interpretation of one decision in a synthetic "
            "simulation. It cannot know your intention, information, or constraints, "
            "and does not establish a stable personal tendency."
        ),
        "reflection_question": REFLECTION_QUESTIONS[event_type],
        "context": {"hasty": user_model.short_term["hasty"],
                    "drawdown_pct": round(user_model.short_term["drawdown"] * 100, 1)},
        "mismatches": [{"claimed": m["claim"], "did": m["behaviour"]} for m in mismatches],
    }


def coach(event, user_model=None, mismatches=None, use_api=True, **_ignored):
    mismatches = mismatches or []
    text, source = None, "offline-generator"
    if use_api:
        candidate = _call_llm(SYSTEM_PROMPT, build_prompt(user_model, event, mismatches))
        if _valid(candidate):
            text, source = candidate, "llm"
    if text is None:
        text = _offline_message(user_model, event, mismatches)
    return {"mode": "llm", "event_type": event["type"], "trait": EVENT_TO_TRAIT[event["type"]],
            "message": text, "source": source, "model": LAST_MODEL if source == "llm" else None,
            "why_this": why_this(user_model, event, mismatches)}
